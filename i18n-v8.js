function getNested(object, path) {
  return path.split(".").reduce((value, key) => value?.[key], object);
}

function applyLanguage(language) {
  const selected = I18N[language] ? language : "id";
  const dictionary = I18N[selected];

  document.documentElement.lang = dictionary.meta.lang;
  document.documentElement.dataset.language = selected;
  document.title = dictionary.meta.title;

  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = dictionary.meta.description;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const value = getNested(dictionary, element.dataset.i18n);
    if (typeof value === "string") element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach(element => {
    const value = getNested(dictionary, element.dataset.i18nHtml);
    if (typeof value === "string") element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(element => {
    const value = getNested(dictionary, element.dataset.i18nAria);
    if (typeof value === "string") element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-language-option]").forEach(button => {
    const active = button.dataset.languageOption === selected;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  try {
    localStorage.setItem("han-an-hua-language", selected);
  } catch (_) {}
}

document.querySelectorAll("[data-language-option]").forEach(button => {
  button.addEventListener("click", () => applyLanguage(button.dataset.languageOption));
});

let initialLanguage = "id";
try {
  const savedLanguage = localStorage.getItem("han-an-hua-language");
  if (savedLanguage && I18N[savedLanguage]) initialLanguage = savedLanguage;
} catch (_) {}

applyLanguage(initialLanguage);
